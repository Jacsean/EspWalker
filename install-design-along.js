  '    svg.push("<text x=\\"" + (p.x + NODE_W / 2) + "\\" y=\\"" + (p.y + NODE_H / 2 + 4) + "\\" text-anchor=\\"middle\\" font-size=\\"12\\" fill=\\"#334\\">" + lib.esc(label) + "</text>");',
  '    svg.push("<title>" + lib.esc(e.id) + "</title>");',
  '    svg.push("</g>");',
  '  });',
  '  svg.push("</svg>");',
