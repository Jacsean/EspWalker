/* ---------- settings.json 合并 ---------- */
const settingsPath = path.join(target, '.reasonix', 'settings.json');
const cmd = function (name) { return 'node .reasonix/skills/design-along/scripts/' + name; };
const additions = {
  UserPromptSubmit: [{ command: cmd('prompt-trigger.js'), description: 'design-along: keyword reminder' }],
  PostToolUse:      [{ command: cmd('post-bash.js'),      description: 'design-along: suggest after commit' }],
  Stop:             [{ command: cmd('stop-candidates.js'), description: 'design-along: candidate list on turn end' }],
  SessionStart:     [{ command: cmd('session-start.js'),  description: 'design-along: inject head index' }]
};
let settings = {};
if (fs.existsSync(settingsPath)) {
  try { settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8')); } catch (e) { settings = {}; }
  if (!fs.existsSync(settingsPath + '.bak')) fs.copyFileSync(settingsPath, settingsPath + '.bak');
}
settings.hooks = settings.hooks || {};
Object.keys(additions).forEach(function (event) {
  settings.hooks[event] = settings.hooks[event] || [];
  additions[event].forEach(function (entry) {
    const dup = settings.hooks[event].some(function (e) { return (e.command || '').indexOf('design-along') >= 0; });
    if (!dup) settings.hooks[event].push(entry);
  });
});
fs.mkdirSync(path.dirname(settingsPath), { recursive: true });
fs.writeFileSync(settingsPath, JSON.stringify(settings, null, 2), 'utf8');
console.log('==> settings.json updated (backup: settings.json.bak)');

