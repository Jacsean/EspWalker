const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const target = path.resolve(process.argv[2] || '.');
if (!fs.existsSync(target)) { console.error('ERROR: target not found: ' + target); process.exit(1); }

const skillDir    = path.join(target, '.reasonix', 'skills', 'design-along');
const scriptsDir  = path.join(skillDir, 'scripts');
const refsDir     = path.join(skillDir, 'references');
const knowledgeDir = path.join(target, 'knowledge');

fs.mkdirSync(scriptsDir, { recursive: true });
fs.mkdirSync(refsDir, { recursive: true });
fs.mkdirSync(knowledgeDir, { recursive: true });

function writeFile(rel, lines) {
  const full = path.join(skillDir, rel);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, Array.isArray(lines) ? lines.join('\n') : lines, 'utf8');
  console.log('  wrote ' + rel);
}

